import fs from 'fs'
import path from 'path'
import {fileURLToPath} from 'url'
import {execa} from 'execa';

export const sleep = (delay) => new Promise((resolve) => setTimeout(resolve, delay))

// true when something is listening on 127.0.0.1:port (used to wait for node RPC ports)
export const portIsOpen = async(port) => {

    try {
        await execa`nc -z 127.0.0.1 ${port.toString()}`
        return true
    } catch {
        return false
    }

}

// The simulator repo root: the nearest ancestor of this file holding example.config.json. Found by walking up
// rather than a fixed number of "..", so moving packages around the workspace cannot break it.
const findRepoRoot = (start) => {
    let dir = start
    while (!fs.existsSync(path.join(dir, 'example.config.json'))) {
        const parent = path.dirname(dir)
        if (parent === dir) {
            throw new Error('cannot find the simulator repo root (no example.config.json above ' + start + ')')
        }
        dir = parent
    }
    return dir
}

export const repoRoot = findRepoRoot(path.dirname(fileURLToPath(import.meta.url)))

// The generator's output directory: GENERATED_DIR if set (relative to the working directory), otherwise the
// repo's own generated/ - so no .env is needed for the usual layout.
export const generatedDir = () => (process.env.GENERATED_DIR ? path.resolve(process.env.GENERATED_DIR) : path.join(repoRoot, 'generated'))

// The network layout make gen wrote (nodes, ports, containers, upgrade plan + height) - what every package works from.
export const loadOverview = () => JSON.parse(fs.readFileSync(path.join(generatedDir(), 'network', 'overview.json'), 'utf8'))

// The compose project's running containers, one object per container ({Name, State, Status, ...}).
export const composeContainers = async () => {
    const {stdout} = await execa`docker compose ps --format json`
    return stdout ? stdout.split('\n').map((line) => JSON.parse(line)) : []
}

// The URLs a node publishes on the host, from its overview.json entry (RPC nodes publish RPC, REST and gRPC).
export const endpoints = (node) => ({
    rpc: `http://localhost:${node.rpc_port}`,
    ws: `ws://localhost:${node.rpc_port}/websocket`,
    grpc: `http://localhost:${node.grpc_port}`,
    rest: `http://localhost:${node.rest_port}`,
})

// The transactions the tx runner sends at set heights (config.json's apps.und.txs, as the generator rendered them).
// None when the file is absent - e.g. a network generated by the bash generator.
export const loadCustomTxs = () => {
    const file = path.join(generatedDir(), 'assets', 'tx_runner', 'custom_txs.json')
    return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {gov: []}
}
